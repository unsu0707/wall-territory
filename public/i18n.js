export const LANGS = { ko: '한국어', ja: '日本語' };

function initialLang() {
  try { const saved = localStorage.getItem('wt_lang'); if (saved && dict[saved]) return saved; } catch {}
  return (navigator.language || '').toLowerCase().startsWith('ja') ? 'ja' : 'ko';
}
export let lang = initialLang();

export function setLang(l) {
  if (!dict[l]) return;
  lang = l;
  try { localStorage.setItem('wt_lang', l); } catch {}
  applyStatic();
}

export function t(key, params = {}) {
  const s = dict[lang][key] ?? dict.ko[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
}

// data-i18n → textContent, data-i18n-html → innerHTML (trusted dict only), data-i18n-ph → placeholder
export function applyStatic() {
  document.documentElement.lang = lang;
  document.title = t('meta.title');
  document.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document.querySelectorAll('[data-i18n-html]').forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml)));
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
  document.querySelectorAll('[data-lang]').forEach((el) => el.classList.toggle('on', el.dataset.lang === lang));
}
